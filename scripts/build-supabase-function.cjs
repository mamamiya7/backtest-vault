'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
function build(){
 const read=name=>fs.readFileSync(path.join(root,'server',name),'utf8').replaceAll('\r\n','\n');
 const server=read('server.cjs');
 const start=server.indexOf('function createHandler('),end=server.indexOf('\nfunction createServer(');
 if(start<0||end<start)throw Error('Account handler structure changed; review bundling.');
 const provider=read('providers.cjs').replace("'use strict';\nconst crypto=require('node:crypto');\n",'').replace('\nmodule.exports={providers};','');
 const adapter=read('edge-adapter.cjs').replace("'use strict';\nconst {Buffer}=require('node:buffer');\nconst {createHandler}=require('./server.cjs');\n",'').replace('\nmodule.exports={createEdgeHandler};','');
 if([provider,adapter].some(s=>/\brequire\(|module\.exports/.test(s)))throw Error('Unsupported module dependency.');
 return '// Generated by scripts/build-supabase-function.cjs. No provider credentials.\nimport * as crypto from "node:crypto";\nimport {Buffer} from "node:buffer";\n'+provider+'\n'+server.slice(start,end)+'\n'+adapter+'\n'+String.raw`const env=Deno.env.toObject();
env.NODE_ENV='production';
const origins=(env.ALLOWED_ORIGINS||'').split(',').filter(Boolean);
if(origins.some(value=>!/^chrome-extension:\/\/[a-p]{32}$/.test(value)))throw Error('Use exact Chrome extension origins.');
const ready=env.PUBLIC_EMAIL_READY==='true'&&origins.length>0;
// Supabase injects its existing project secrets; they are never pasted into source.
let provider;
if(ready)provider=providers(env);
const handle=createEdgeHandler({provider,origins,ready});
Deno.serve(handle);
`;
}
if(require.main===module){const destination=path.join(root,'supabase/functions/vault-accounts/index.ts');fs.mkdirSync(path.dirname(destination),{recursive:true});fs.writeFileSync(destination,build());console.log('Prepared credential-free Supabase function source. Public account access defaults to closed.');}
module.exports={build};
